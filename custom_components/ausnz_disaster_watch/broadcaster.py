"""Emergency broadcaster: the ABC Local Radio station (RNZ in New Zealand) for a location (#73).

In Australia ABC Local Radio is the official emergency broadcaster; in New Zealand RNZ is a
lifeline broadcaster. The stations come from the bundled table
``data/emergency_broadcasters.json``, generated by ``script/update-broadcasters`` from the
Radio Browser directory (PDDL 1.0) and the ABC and RNZ station pages. Nothing is fetched at
runtime: the integration only links to each broadcaster's own HTTPS stream, which the media
player fetches directly.

The nearest station is the one whose directory location (its studio) is closest to the
monitored point, which is not always the station that covers a town, so the options let the
user pick a station instead.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import cache
import json
from pathlib import Path
from typing import TYPE_CHECKING, Final

from homeassistant.config_entries import ConfigEntry

from .const import CONF_EMERGENCY_BROADCASTER, DOMAIN, STATE_NZ
from .coordinator import calculate_haversine_distance

if TYPE_CHECKING:
    from homeassistant.core import HomeAssistant

_TABLE_PATH: Final = Path(__file__).parent / "data" / "emergency_broadcasters.json"

# Option values besides a station key
BROADCASTER_OFF: Final = "off"
BROADCASTER_NEAREST: Final = "nearest"
# Media source identifier prefix: media-source://ausnz_disaster_watch/emergency_broadcaster/<entry_id>
MEDIA_PREFIX: Final = "emergency_broadcaster"


@dataclass(frozen=True, slots=True)
class Broadcaster:
    """One station of the bundled table."""

    key: str
    name: str
    network: str
    country: str
    state: str
    region: str
    latitude: float
    longitude: float
    stream_url: str
    mime_type: str
    station_page: str


@dataclass(frozen=True, slots=True)
class BroadcasterChoice:
    """The station an entry uses, how it was chosen and how far its location is."""

    station: Broadcaster
    selection: str  # "nearest" or "chosen"
    distance_km: float


@cache
def load_broadcasters() -> dict[str, Broadcaster]:
    """Load the bundled station table by key.

    This reads a file (once), so call it from an executor job, not the event loop. The
    returned mapping is cached and shared: treat it as read-only.
    """
    with _TABLE_PATH.open(encoding="utf-8") as file:
        rows = json.load(file)["stations"]
    return {
        row["key"]: Broadcaster(
            key=row["key"],
            name=row["name"],
            network=row["network"],
            country=row["country"],
            state=row["state"],
            region=row["region"],
            latitude=float(row["latitude"]),
            longitude=float(row["longitude"]),
            stream_url=row["stream_url"],
            mime_type=row["mime_type"],
            station_page=row["station_page"],
        )
        for row in rows
    }


async def async_load_broadcasters(hass: HomeAssistant) -> dict[str, Broadcaster]:
    """Load the station table in an executor job."""
    return await hass.async_add_executor_job(load_broadcasters)


def country_of(state: str) -> str:
    """Return the table country of an entry's state code."""
    return "NZ" if state.upper() == STATE_NZ else "AU"


def stations_by_distance(
    stations: dict[str, Broadcaster], state: str, latitude: float, longitude: float
) -> list[tuple[Broadcaster, float]]:
    """Return the stations of the entry's country, nearest first, with their distance in km."""
    country = country_of(state)
    ranked = [
        (station, calculate_haversine_distance(latitude, longitude, station.latitude, station.longitude))
        for station in stations.values()
        if station.country == country
    ]
    return sorted(ranked, key=lambda item: (item[1], item[0].key))


def broadcaster_option(entry: ConfigEntry) -> str:
    """Return the entry's broadcaster option: off, nearest or a station key."""
    return str(entry.options.get(CONF_EMERGENCY_BROADCASTER, BROADCASTER_OFF))


def broadcaster_enabled(entry: ConfigEntry) -> bool:
    """Return True if the emergency broadcaster is turned on for the entry."""
    return broadcaster_option(entry) != BROADCASTER_OFF


def choose_broadcaster(
    stations: dict[str, Broadcaster], option: str, state: str, latitude: float, longitude: float
) -> BroadcasterChoice | None:
    """Return the chosen station, or the nearest one; None when off or the table has no station."""
    if option == BROADCASTER_OFF:
        return None
    if (chosen := stations.get(option)) is not None:
        distance = calculate_haversine_distance(latitude, longitude, chosen.latitude, chosen.longitude)
        return BroadcasterChoice(chosen, "chosen", distance)
    # "nearest", or a station that is no longer in the table
    if not (ranked := stations_by_distance(stations, state, latitude, longitude)):
        return None
    station, distance = ranked[0]
    return BroadcasterChoice(station, BROADCASTER_NEAREST, distance)


def media_content_id(entry_id: str) -> str:
    """Return the media source ID that always plays the entry's current broadcaster."""
    return f"media-source://{DOMAIN}/{MEDIA_PREFIX}/{entry_id}"
